-- Migration V3: Hoàn thiện toàn bộ lược đồ theo tài liệu thiết kế (ERD mục 2.2)
-- Bao gồm: Classes, Student_Classes, Explanation cho Questions,
-- Exams, Exam_Questions, Exam_Attempts, Exam_Answers, Exam_Answer_Options,
-- AI_Generation_Jobs và các ràng buộc, chỉ mục hiệu năng.
-- =============================================================================

-- 1. Bổ sung trường ngày sinh cho bảng users
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS date_of_birth DATE;

-- 2. Bảng lớp học (Classes)
CREATE TABLE IF NOT EXISTS classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Bảng liên kết sinh viên - lớp học (Student_Classes)
CREATE TABLE IF NOT EXISTS student_classes (
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (student_id, class_id)
);

CREATE INDEX IF NOT EXISTS idx_student_classes_student_id ON student_classes(student_id);
CREATE INDEX IF NOT EXISTS idx_student_classes_class_id ON student_classes(class_id);

-- 4. Bổ sung trường lời giải thích và độ khó cho câu hỏi (Questions)
ALTER TABLE questions
    ADD COLUMN IF NOT EXISTS explanation TEXT,
    ADD COLUMN IF NOT EXISTS difficulty VARCHAR(20) NOT NULL DEFAULT 'MEDIUM'
        CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'));

-- 5. Bảng kỳ thi (Exams)
CREATE TABLE IF NOT EXISTS exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES teacher_groups(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    duration_minutes INT NOT NULL CHECK (duration_minutes > 0),
    pin VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_exam_time CHECK (end_time > start_time)
);

CREATE INDEX IF NOT EXISTS idx_exams_group_id ON exams(group_id);
CREATE INDEX IF NOT EXISTS idx_exams_status ON exams(status);
CREATE INDEX IF NOT EXISTS idx_exams_created_by ON exams(created_by);

-- 6. Bảng trung gian câu hỏi trong đề thi (Exam_Questions)
CREATE TABLE IF NOT EXISTS exam_questions (
    exam_id BIGINT NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
    question_order INT NOT NULL CHECK (question_order > 0),
    score DECIMAL(5, 2) NOT NULL DEFAULT 1.0 CHECK (score >= 0),
    PRIMARY KEY (exam_id, question_id),
    UNIQUE (exam_id, question_order)
);

CREATE INDEX IF NOT EXISTS idx_exam_questions_exam_id ON exam_questions(exam_id);
CREATE INDEX IF NOT EXISTS idx_exam_questions_question_id ON exam_questions(question_id);

-- 7. Bảng lượt làm bài của sinh viên (Exam_Attempts)
-- Ràng buộc: Mỗi sinh viên duy nhất một attempt cho mỗi kỳ thi (idempotent start/resume)
CREATE TABLE IF NOT EXISTS exam_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deadline TIMESTAMPTZ NOT NULL,
    submitted_at TIMESTAMPTZ,
    total_score DECIMAL(5, 2) CHECK (total_score >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'AUTO_SUBMITTED')),
    UNIQUE (exam_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_exam_attempts_student_id ON exam_attempts(student_id);
CREATE INDEX IF NOT EXISTS idx_exam_attempts_exam_status ON exam_attempts(exam_id, status);

-- 8. Bảng câu trả lời của sinh viên (Exam_Answers)
-- Ràng buộc: UNIQUE (attempt_id, question_id) làm nền tảng cho upsert autosave
CREATE TABLE IF NOT EXISTS exam_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES exam_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
    answer_text TEXT,
    score DECIMAL(5, 2) CHECK (score >= 0),
    answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (attempt_id, question_id)
);

CREATE INDEX IF NOT EXISTS idx_exam_answers_attempt_id ON exam_answers(attempt_id);
CREATE INDEX IF NOT EXISTS idx_exam_answers_question_id ON exam_answers(question_id);

-- 9. Bảng lựa chọn được chọn trong bài làm trắc nghiệm (Exam_Answer_Options)
CREATE TABLE IF NOT EXISTS exam_answer_options (
    answer_id BIGINT NOT NULL REFERENCES exam_answers(id) ON DELETE CASCADE,
    option_id BIGINT NOT NULL REFERENCES options(id) ON DELETE CASCADE,
    PRIMARY KEY (answer_id, option_id)
);

CREATE INDEX IF NOT EXISTS idx_exam_answer_options_answer_id ON exam_answer_options(answer_id);
CREATE INDEX IF NOT EXISTS idx_exam_answer_options_option_id ON exam_answer_options(option_id);

-- 10. Bảng tiến trình sinh câu hỏi bằng AI (AI_Generation_Jobs)
CREATE TABLE IF NOT EXISTS ai_generation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    file_path VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    result TEXT,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_ai_jobs_teacher_id ON ai_generation_jobs(teacher_id);
CREATE INDEX IF NOT EXISTS idx_ai_jobs_status ON ai_generation_jobs(status);
