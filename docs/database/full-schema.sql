-- Tùy chọn dọn dẹp các bảng cũ nếu cần tạo lại từ đầu
DROP TABLE IF EXISTS ai_generation_jobs CASCADE;
DROP TABLE IF EXISTS exam_answer_options CASCADE;
DROP TABLE IF EXISTS exam_answers CASCADE;
DROP TABLE IF EXISTS exam_attempts CASCADE;
DROP TABLE IF EXISTS exam_questions CASCADE;
DROP TABLE IF EXISTS exams CASCADE;
DROP TABLE IF EXISTS options CASCADE;
DROP TABLE IF EXISTS questions CASCADE;
DROP TABLE IF EXISTS teacher_group_members CASCADE;
DROP TABLE IF EXISTS teacher_groups CASCADE;
DROP TABLE IF EXISTS subjects CASCADE;
DROP TABLE IF EXISTS student_classes CASCADE;
DROP TABLE IF EXISTS classes CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- =============================================================================
-- 1. BẢNG NGƯỜI DÙNG (USERS)
-- Quản trị viên, Giảng viên và Sinh viên
-- =============================================================================
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
    date_of_birth DATE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_username ON users(username);

-- =============================================================================
-- 2. BẢNG LỚP HỌC (CLASSES) & PHÂN LỚP SINH VIÊN (STUDENT_CLASSES)
-- Phục vụ quản lý danh sách lớp và sinh viên theo lớp
-- =============================================================================
CREATE TABLE classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE student_classes (
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (student_id, class_id)
);

CREATE INDEX idx_student_classes_student_id ON student_classes(student_id);
CREATE INDEX idx_student_classes_class_id ON student_classes(class_id);

-- =============================================================================
-- 3. BẢNG MÔN HỌC (SUBJECTS)
-- Danh mục môn học cơ sở và chuyên ngành
-- =============================================================================
CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_subjects_code ON subjects(code);

-- =============================================================================
-- 4. BẢNG NHÓM GIẢNG VIÊN (TEACHER_GROUPS) & THÀNH VIÊN (TEACHER_GROUP_MEMBERS)
-- Giảng viên quản lý ngân hàng câu hỏi và đề thi theo nhóm môn học
-- =============================================================================
CREATE TABLE teacher_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (subject_id, name)
);

CREATE INDEX idx_teacher_groups_subject_id ON teacher_groups(subject_id);

CREATE TABLE teacher_group_members (
    group_id BIGINT NOT NULL REFERENCES teacher_groups(id) ON DELETE CASCADE,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (group_id, teacher_id)
);

CREATE INDEX idx_teacher_group_members_teacher ON teacher_group_members(teacher_id);

-- =============================================================================
-- 5. BẢNG NGÂN HÀNG CÂU HỎI (QUESTIONS) & PHƯƠNG ÁN LỰA CHỌN (OPTIONS)
-- Hỗ trợ 3 loại câu hỏi: SINGLE_CHOICE, MULTIPLE_CHOICE, SHORT_ANSWER
-- =============================================================================
CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_group_id BIGINT NOT NULL REFERENCES teacher_groups(id) ON DELETE CASCADE,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    content TEXT NOT NULL CHECK (length(btrim(content)) > 0),
    question_type VARCHAR(30) NOT NULL
        CHECK (question_type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE', 'SHORT_ANSWER')),
    difficulty VARCHAR(20) NOT NULL DEFAULT 'MEDIUM'
        CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    explanation TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_questions_teacher_group_id ON questions(teacher_group_id);
CREATE INDEX idx_questions_created_by ON questions(created_by);
CREATE INDEX idx_questions_type ON questions(question_type);

CREATE TABLE options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    content TEXT NOT NULL CHECK (length(btrim(content)) > 0),
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    option_order INT NOT NULL CHECK (option_order > 0),
    UNIQUE (question_id, option_order)
);

CREATE INDEX idx_options_question_id ON options(question_id);

-- =============================================================================
-- 6. BẢNG KỲ THI (EXAMS) & CÂU HỎI TRONG ĐỀ THI (EXAM_QUESTIONS)
-- Khóa đề: Sau khi PUBLISHED hoặc CLOSED không cho sửa câu hỏi & điểm
-- =============================================================================
CREATE TABLE exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES teacher_groups(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    duration_minutes INT NOT NULL CHECK (duration_minutes > 0),
    pin VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_exam_time CHECK (end_time > start_time)
);

CREATE INDEX idx_exams_group_id ON exams(group_id);
CREATE INDEX idx_exams_status ON exams(status);
CREATE INDEX idx_exams_created_by ON exams(created_by);

CREATE TABLE exam_questions (
    exam_id BIGINT NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
    question_order INT NOT NULL CHECK (question_order > 0),
    score DECIMAL(5, 2) NOT NULL DEFAULT 1.0 CHECK (score >= 0),
    PRIMARY KEY (exam_id, question_id),
    UNIQUE (exam_id, question_order)
);

CREATE INDEX idx_exam_questions_exam_id ON exam_questions(exam_id);
CREATE INDEX idx_exam_questions_question_id ON exam_questions(question_id);

-- =============================================================================
-- 7. BẢNG LƯỢT LÀM BÀI (EXAM_ATTEMPTS)
-- Ràng buộc UNIQUE (exam_id, student_id): Mỗi SV 1 attempt duy nhất (Idempotent)
-- Deadline phía server = min(started_at + duration, exam.end_time)
-- =============================================================================
CREATE TABLE exam_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deadline TIMESTAMPTZ NOT NULL,
    submitted_at TIMESTAMPTZ,
    total_score DECIMAL(5, 2) CHECK (total_score >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'AUTO_SUBMITTED')),
    UNIQUE (exam_id, student_id)
);

CREATE INDEX idx_exam_attempts_student_id ON exam_attempts(student_id);
CREATE INDEX idx_exam_attempts_exam_status ON exam_attempts(exam_id, status);

-- =============================================================================
-- 8. BẢNG CÂU TRẢ LỜI (EXAM_ANSWERS) & LỰA CHỌN CHỌN (EXAM_ANSWER_OPTIONS)
-- Ràng buộc UNIQUE (attempt_id, question_id): Nền tảng cho upsert autosave
-- =============================================================================
CREATE TABLE exam_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES exam_attempts(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE RESTRICT,
    answer_text TEXT,
    score DECIMAL(5, 2) CHECK (score >= 0),
    answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (attempt_id, question_id)
);

CREATE INDEX idx_exam_answers_attempt_id ON exam_answers(attempt_id);
CREATE INDEX idx_exam_answers_question_id ON exam_answers(question_id);

CREATE TABLE exam_answer_options (
    answer_id BIGINT NOT NULL REFERENCES exam_answers(id) ON DELETE CASCADE,
    option_id BIGINT NOT NULL REFERENCES options(id) ON DELETE CASCADE,
    PRIMARY KEY (answer_id, option_id)
);

CREATE INDEX idx_exam_answer_options_answer_id ON exam_answer_options(answer_id);
CREATE INDEX idx_exam_answer_options_option_id ON exam_answer_options(option_id);

-- =============================================================================
-- 9. BẢNG TIẾN TRÌNH SINH CÂU HỎI AI (AI_GENERATION_JOBS)
-- Quản lý tiến trình xử lý bất đồng bộ từ file PDF qua Gemini API
-- =============================================================================
CREATE TABLE ai_generation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    file_path VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    result TEXT,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ
);

CREATE INDEX idx_ai_jobs_teacher_id ON ai_generation_jobs(teacher_id);
CREATE INDEX idx_ai_jobs_status ON ai_generation_jobs(status);
